"""
Serves real eval harness output (evaluation/results*.json, generated by
evaluation/run_eval.py) to the dashboard. This intentionally reads whatever
the eval harness actually produced on disk -- not a hardcoded/mocked
metrics object -- so the Evaluation dashboard page always reflects a real
run, or clearly reports that none exists yet rather than fabricating one.
"""
import json  # noqa: I001
from pathlib import Path

from fastapi import APIRouter, Depends, HTTPException

from app.auth.oauth import get_current_user

router = APIRouter(prefix="/evaluation", tags=["evaluation"])

_EVAL_DIR = Path(__file__).parent.parent.parent.parent / "evaluation"

_KNOWN_RESULT_FILES = {
    "bandit_only": "results_bandit_only.json",
    "merged": "results_merged.json",
    "merged_hf": "results_merged_hf.json",
    "bandit_only_hf": "results_bandit_only_hf.json",
}


@router.get("/latest")
def get_latest_evaluation(user: dict = Depends(get_current_user)) -> dict:  # noqa: B008
    """
    Returns whichever real eval result files currently exist on disk. Each
    key is present only if `python3 evaluation/run_eval.py [flags]` has
    actually been run and produced that specific variant -- there is no
    fallback to fabricated numbers.
    """
    found = {}
    for variant, filename in _KNOWN_RESULT_FILES.items():
        path = _EVAL_DIR / filename
        if path.exists():
            found[variant] = json.loads(path.read_text())

    if not found:
        raise HTTPException(
            status_code=404,
            detail=(
                "No eval results found on disk. Run 'python3 evaluation/run_eval.py' "
                "(and optionally --bandit-only / --use-hf) first."
            ),
        )
    return found
